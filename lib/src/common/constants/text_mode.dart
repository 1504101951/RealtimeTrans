/// 选区卡片的文本处理模式；翻译之外的模式由模型服务使用「处理提示词」处理（#100）。
enum TextMode {
  /// 翻译为目标语言。
  translate,

  /// 润色：保持原文语言与原意，改进表达。
  polish,

  /// 纠错：修正拼写、语法与标点。
  correct,

  /// 解释：用主要语言说明含义与难点。
  explain,
}

